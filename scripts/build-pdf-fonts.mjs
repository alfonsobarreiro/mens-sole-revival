#!/usr/bin/env node
/**
 * Converts the brand TTFs in /public/fonts/ into pre-baked jsPDF font
 * modules under /lib/pdfFonts/. Each generated module hooks into
 * jsPDF.API.events so that when `new jsPDF()` is called anywhere in
 * the codebase, the font is registered automatically.
 *
 * This is the approach jsPDF's own fontconverter tool uses. Calling
 * doc.addFileToVFS + doc.addFont AFTER instantiation is flaky for
 * arbitrary TTFs; the events.addFonts hook is the stable path.
 *
 * Run once after changing font files:
 *   node scripts/build-pdf-fonts.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");

const fonts = [
  { ttf: "BarlowCondensed-Bold", family: "BarlowCondensed", style: "bold"   },
  { ttf: "DMSans-Regular",       family: "DMSans",          style: "normal" },
  { ttf: "DMSans-Bold",          family: "DMSans",          style: "bold"   },
  { ttf: "DMSans-Medium",        family: "DMSansMedium",    style: "normal" },
  { ttf: "Lora-Regular",         family: "Lora",            style: "normal" },
  { ttf: "Lora-Bold",            family: "Lora",            style: "bold"   },
];

mkdirSync(resolve(repoRoot, "lib/pdfFonts"), { recursive: true });

let total = 0;
for (const { ttf, family, style } of fonts) {
  const ttfPath = resolve(repoRoot, "public/fonts", `${ttf}.ttf`);
  const buf = readFileSync(ttfPath);
  const base64 = buf.toString("base64");
  total += base64.length;

  const moduleCode =
    `// AUTOGENERATED by scripts/build-pdf-fonts.mjs — do not edit by hand.\n` +
    `// Source: public/fonts/${ttf}.ttf · ${(buf.length / 1024).toFixed(0)} KB TTF\n` +
    `//\n` +
    `// Importing this module pre-registers the font with jsPDF via the\n` +
    `// events.addFonts hook. The next \`new jsPDF()\` call embeds the font.\n` +
    `\n` +
    `import { jsPDF } from "jspdf";\n` +
    `\n` +
    `const font =\n  "${base64}";\n` +
    `\n` +
    `function callAddFont(this: jsPDF) {\n` +
    `  this.addFileToVFS("${ttf}.ttf", font);\n` +
    `  this.addFont("${ttf}.ttf", "${family}", "${style}");\n` +
    `}\n` +
    `\n` +
    `// @ts-expect-error — jsPDF.API.events isn't in the published types.\n` +
    `(jsPDF as unknown as { API: { events: Array<[string, unknown]> } }).API.events.push([\n` +
    `  "addFonts",\n` +
    `  callAddFont,\n` +
    `]);\n`;

  const outPath = resolve(repoRoot, "lib/pdfFonts", `${ttf}.ts`);
  writeFileSync(outPath, moduleCode);
  console.log(
    `  ${ttf.padEnd(24)} → ${(buf.length / 1024).toFixed(0).padStart(4)} KB TTF, ${(base64.length / 1024).toFixed(0).padStart(4)} KB base64`
  );
}

console.log(`\nGenerated ${fonts.length} font modules (~${(total / 1024 / 1024).toFixed(1)} MB base64 total in /lib/pdfFonts/).`);
